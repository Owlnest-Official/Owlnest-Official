// Reproducible production Nginx configuration. Does not deploy or edit VPS files.
// Caddy remains responsible for TLS, compression, and the existing API upstreams.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),{redirects}=require('../config/site-routes.json');
const aliases={...redirects,'/account':'/account/','/policy':'/disclaimer','/policy/':'/disclaimer','/contact/':'/contact','/reviews/':'/reviews','/manual/':'/manual','/disclaimer/':'/disclaimer','/preorder-policy/':'/preorder-policy','/what-is-owlnest-lume':'/what-is-owlnest-lume/','/sleep-ready-room-check':'/sleep-ready-room-check/'};
for(const p of ['contact','reviews','manual','disclaimer','preorder-policy','what-is-owlnest-lume','sleep-ready-room-check'])aliases['/zh-tw/'+p]='/zh-tw/'+p+'/';
const esc=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
for(const [from,to]of Object.entries(aliases))if(!from.startsWith('/')||!to.startsWith('/')||to.startsWith('//')||/[\s;$"{}]/.test(from+to))throw Error('Unsafe route contract');
const conf=`# Generated by scripts/generate-vps-nginx.cjs; V7.5.
# Match original request URI, not internal index.html rewrites (avoids loops).
map $request_uri $owlnest_legacy_route {
    default "";
${Object.entries(aliases).sort(([a],[b])=>a.localeCompare(b)).map(([a,b])=>`    ~^${esc(a)}(?:\\?|$) ${b};`).join('\n')}
}
# A referral path is authoritative, matching the old first-ref behavior.
# Remove one conflicting ref without changing encoding or any other parameter.
map $args $owlnest_ref_args {
    default $args;
    ~*^ref=[^&]*$ "";
    ~*^ref=[^&]*&(?<ref_after>.*)$ $ref_after;
    ~*^(?<ref_before>.+)&ref=[^&]*$ $ref_before;
    ~*^(?<ref_left>.+)&ref=[^&]*&(?<ref_right>.*)$ $ref_left&$ref_right;
}
map $owlnest_ref_args $owlnest_ref_suffix { "" ""; default &$owlnest_ref_args; }
map $args $owlnest_duplicate_ref { default 0; ~*(^|&)ref=[^&]*.*&ref= 1; }
map $args $owlnest_qr_query { default $args; "" "utm_source=qr&utm_medium=offline&utm_campaign=legacy_qr&utm_content=home_cn"; }
map $arg_v $owlnest_script_cache { "" "public, max-age=0, must-revalidate"; default "public, max-age=604800"; }
server {
    listen 80;
    listen [::]:80;
    server_name _;
    server_tokens off;
    absolute_redirect off;
    root /usr/share/nginx/html;
    index index.html;
    charset utf-8;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy strict-origin-when-cross-origin always;
    add_header Cache-Control "no-cache" always;
    if ($owlnest_legacy_route) { return 301 $owlnest_legacy_route$is_args$args; }

    location = /health { access_log off; default_type text/plain; return 200 "ok\\n"; }
    # Keep historical image compatibility; the rewritten destination runs guards.
    location = /.netlify/images {
        if ($arg_url = "") { return 400; }
        if ($arg_url !~ "^/[^/]") { return 400; }
        rewrite ^ $arg_url last;
    }
    location = /首頁 { return 302 /?$owlnest_qr_query; }
    location = /activate { try_files /activate.html =404; }
    location = /verify { try_files /verify.html =404; }
    location = /account/activate { try_files /activate.html =404; }
    location = /account/verify { try_files /verify.html =404; }
    location ~ "^/r/(?<ref_code>[A-Za-z0-9][A-Za-z0-9_-]{0,63})/?$" {
        if ($owlnest_duplicate_ref) { return 400; }
        return 302 /products/?ref=$ref_code$owlnest_ref_suffix;
    }
    # Internal source/config is never public, even if its suffix looks like an asset.
    location ~* ^/(docs|server|scripts|config|infra|netlify|supabase|_incoming|node_modules|tests)(/|$) { return 404; }
    location ~ /\\.(?!well-known(?:/|$)) { return 404; }
    location ~* \\.(?:md|cjs|map|env|ini|log|sql|sqlite|sqlite3|bak|backup|pem|key|yml|yaml|toml|lock|ps1|sh|py)(?:$|/) { return 404; }
    location = /package.json { return 404; }
    location = /package-lock.json { return 404; }
    location ~ "^/assets/optimized/css/[a-f0-9]{16}\\.css$" {
        try_files $uri =404;
        add_header Cache-Control "public, max-age=31536000, immutable";
        add_header X-Content-Type-Options nosniff always;
    }
    location ~* \\.(css|js|mjs)$ {
        try_files $uri =404;
        add_header Cache-Control $owlnest_script_cache;
        add_header X-Content-Type-Options nosniff always;
    }
    location ~* \\.(jpg|jpeg|png|gif|webp|avif|svg|ico|woff|woff2|ttf|mp4|webm|pdf|json)$ {
        try_files $uri =404;
        add_header Cache-Control "public, max-age=604800";
        add_header X-Content-Type-Options nosniff always;
    }
    location / { try_files $uri $uri/ $uri.html =404; }
}
`;
const dest=path.join(root,'infra/vps/nginx/default.conf');fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,conf);console.log(dest);
