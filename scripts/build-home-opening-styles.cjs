// Homepage-only bundles. Keep the approved language-specific cascade unchanged.
// Shared sources and unrelated page styles are never written by this script.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const css = path.join(root, 'assets/css');
const bundle = (names) => '/* Generated by scripts/build-home-opening-styles.cjs. */\n' +
  names.map(name => `/* ${name} */\n${fs.readFileSync(path.join(css, name), 'utf8').replace(/\r\n/g, '\n')}`).join('\n');
for (const lang of ['en', 'zh']) {
  const foundation = ['tailwind-public.css', 'core-fonts.css', ...(lang === 'zh' ? ['home-brand-opening-fonts.css'] : []), 'navigation-icons.css'];
  const middle = lang === 'zh' ? ['after-hours.css', 'home.css'] : ['home.css', 'after-hours.css'];
  const page = ['consent.css', 'typography.css', ...middle, 'site-navigation.css', 'home-revision-03.css', 'home-brand-opening.css'];
  fs.writeFileSync(path.join(css, `home-opening-foundation-${lang}.css`), bundle(foundation));
  fs.writeFileSync(path.join(css, `home-opening-page-${lang}.css`), bundle(page));
}
console.log('Built four homepage CSS bundles; shared source files unchanged.');
